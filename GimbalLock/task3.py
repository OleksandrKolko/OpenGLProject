import numpy as np
from src.math.Mat4x4 import Mat4x4

# Задані кути
alpha, beta, gamma = np.radians(45), np.radians(30), np.radians(60)

print("=" * 60)
print("ЗАВДАННЯ 3: Конвенції та послідовність обертань")
print("=" * 60)
print(f"Кути: alpha={np.degrees(alpha):.0f}°, beta={np.degrees(beta):.0f}°, gamma={np.degrees(gamma):.0f}°")
print()

# -------------------------------------------------------------------
# 1. Конвенція XYZ (зовнішні осі)
#    Обертання: спочатку навколо X, потім Y, потім Z
#    Матриця: R = Rz * Ry * Rx
# -------------------------------------------------------------------
print("1. Матриця обертання для конвенції XYZ (зовнішні осі):")
print("   Порядок: спочатку X, потім Y, потім Z")
print("   Формула: R_XYZ = Rz(gamma) * Ry(beta) * Rx(alpha)")

R_XYZ = Mat4x4.rotation_euler(alpha, beta, gamma, Mat4x4.XYZ)
print(R_XYZ)

# -------------------------------------------------------------------
# 2. Конвенція ZYX (зовнішні осі)
#    Обертання: спочатку навколо Z, потім Y, потім X
#    Матриця: R = Rx * Ry * Rz
# -------------------------------------------------------------------
print("\n2. Матриця обертання для конвенції ZYX (зовнішні осі):")
print("   Порядок: спочатку Z, потім Y, потім X")
print("   Формула: R_ZYX = Rx(alpha) * Ry(beta) * Rz(gamma)")

R_ZYX = Mat4x4.rotation_euler(alpha, beta, gamma, Mat4x4.ZYX)
print(R_ZYX)

# -------------------------------------------------------------------
# 3. Порівняння матриць
# -------------------------------------------------------------------
print("\n3. Порівняння матриць:")
print("   Чи однакові матриці XYZ і ZYX? ", end="")

# Перевірка на схожість (елемент за елементом)
are_equal = np.allclose(R_XYZ.data, R_ZYX.data)
print("ТАК" if are_equal else "НІ")

# Різниця між матрицями
print("\n   Різниця матриць (XYZ - ZYX):")
print(R_XYZ.data - R_ZYX.data)

# -------------------------------------------------------------------
# 4. Порівняння координат вершин
# -------------------------------------------------------------------
print("\n4. Координати вершин куба після обертання:")

# Діагональні вершини
v1 = np.array([0, 0, 0, 1])
v2 = np.array([1, 1, 1, 1])

v1_xyz = R_XYZ.data @ v1
v2_xyz = R_XYZ.data @ v2

v1_zyx = R_ZYX.data @ v1
v2_zyx = R_ZYX.data @ v2

print(f"   Вершина (0,0,0):")
print(f"      XYZ: ({v1_xyz[0]:.4f}, {v1_xyz[1]:.4f}, {v1_xyz[2]:.4f})")
print(f"      ZYX: ({v1_zyx[0]:.4f}, {v1_zyx[1]:.4f}, {v1_zyx[2]:.4f})")

print(f"   Вершина (1,1,1):")
print(f"      XYZ: ({v2_xyz[0]:.4f}, {v2_xyz[1]:.4f}, {v2_xyz[2]:.4f})")
print(f"      ZYX: ({v2_zyx[0]:.4f}, {v2_zyx[1]:.4f}, {v2_zyx[2]:.4f})")    